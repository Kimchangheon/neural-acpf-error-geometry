def to_gridfm_inputs(batch: Dict[str, torch.Tensor], device, feature_transform="signed_log"):
    """OPFData batch -> GridFM's bus/gen feature layout."""
    from train_valid_test_gridfm import (
        PD_H, QD_H, QG_H, VM_H, VA_H, PQ_H, PV_H, REF_H, MIN_VM_H, MAX_VM_H,
        MIN_QG_H, MAX_QG_H, GS, BS, VN_KV, PG_H, MIN_PG, MAX_PG, C1_H, G_ON,
        signed_log1p, make_branch_edge_features,
    )
    S = batch["S_start"].squeeze(0).to(device)
    bt = batch["bus_type"].squeeze(0).to(device)
    n = S.shape[0]
    x_bus = torch.zeros((n, 15), dtype=torch.float32, device=device)
    p_in, q_in = -S.real.float(), -S.imag.float()
    if feature_transform == "signed_log":
        p_in, q_in = signed_log1p(p_in), signed_log1p(q_in)
    x_bus[:, PD_H] = p_in
    x_bus[:, QD_H] = q_in
    x_bus[:, VM_H] = batch["V_start"].squeeze(0)[:, 0].float().to(device)
    x_bus[:, VA_H] = batch["V_start"].squeeze(0)[:, 1].float().to(device)
    # OPFData bus_type follows MATPOWER: 1=PQ, 2=PV, 3=ref
    x_bus[:, PQ_H] = (bt == 1).float()
    x_bus[:, PV_H] = (bt == 2).float()
    x_bus[:, REF_H] = (bt == 3).float()
    x_bus[:, MIN_VM_H] = batch["Bus_vmin"].squeeze(0).float().to(device)
    x_bus[:, MAX_VM_H] = batch["Bus_vmax"].squeeze(0).float().to(device)
    x_bus[:, MIN_QG_H] = batch["Gen_q_min"].squeeze(0).float().to(device)
    x_bus[:, MAX_QG_H] = batch["Gen_q_max"].squeeze(0).float().to(device)
    x_bus[:, VN_KV] = torch.log10(batch["vn_kv"].squeeze(0).float().to(device) + 1e-9)

    # Index the (CPU) batch tensors with a CPU index, then move: mixing a CUDA
    # index with a CPU tensor raises "indices should be either on cpu or on the
    # same device as the indexed tensor".
    ctrl_cpu = batch["Gen_controllable"].squeeze(0) > 0
    gen_bus_cpu = torch.where(ctrl_cpu)[0]
    if gen_bus_cpu.numel() == 0:
        gen_bus_cpu = torch.tensor([0], dtype=torch.long)
    gen_bus = gen_bus_cpu.to(device)
    x_gen = torch.zeros((gen_bus_cpu.numel(), 7), dtype=torch.float32, device=device)
    x_gen[:, MIN_PG] = batch["Gen_p_min"].squeeze(0)[gen_bus_cpu].float().to(device)
    x_gen[:, MAX_PG] = batch["Gen_p_max"].squeeze(0)[gen_bus_cpu].float().to(device)
    x_gen[:, C1_H] = batch["Gen_cost_c1"].squeeze(0)[gen_bus_cpu].float().to(device)
    x_gen[:, G_ON] = 1.0

    edge_bus, edge_attr_bus = gridfm_branch_edges(batch, device, feature_transform)
    gi = torch.arange(gen_bus_cpu.numel(), dtype=torch.long, device=device)
    x_dict = {"bus": x_bus, "gen": x_gen}
    edge_index_dict = {
        ("bus", "connects", "bus"): edge_bus,
        ("gen", "connected_to", "bus"): torch.stack([gi, gen_bus], dim=0),
        ("bus", "connected_to", "gen"): torch.stack([gen_bus, gi], dim=0),
    }
    edge_attr_dict = {("bus", "connects", "bus"): edge_attr_bus}
    return x_dict, edge_index_dict, edge_attr_dict


def gridfm_branch_edges(batch, device, feature_transform="signed_log"):
    """Branch edges for GridFM, derived from the batch Y-bus off-diagonals."""
    from train_valid_test_gridfm import signed_log1p

    Y = batch["Ybus"]
    if Y.dim() > 2:
        Y = Y.squeeze(0)
    if Y.is_sparse:
        c = Y.coalesce()
        idx, vals = c.indices(), c.values()
        keep = (idx[0] != idx[1]) & (vals.abs() > 0)
        ei = idx[:, keep].to(device)
        y = vals[keep]
    else:
        idx = (Y.abs() > 0).nonzero(as_tuple=False)
        idx = idx[idx[:, 0] != idx[:, 1]]
        ei = idx.t().to(device)
        y = Y[idx[:, 0], idx[:, 1]]
    attr = torch.stack([y.real.float(), y.imag.float()], dim=-1).to(device)
    if feature_transform == "signed_log":
        attr = signed_log1p(attr)
    return ei, attr
